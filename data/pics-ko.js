// Card picture for a word, or "" when it has none. Paths resolve from this module, not the page.
export function picHTML(ko, esc, small = false) {
  if (PIC[ko]) {
    const src = new URL(`../${PIC_DIR}${PIC[ko]}.svg`, import.meta.url).href;
    return `<img class="${small ? "bpic" : "picimg"}" src="${esc(src)}" alt="" loading="lazy" title="Mulberry Symbols · CC BY-SA 4.0">`;
  }
  if (EMOJI[ko]) return `<span class="${small ? "bemoji" : "picemoji"}" aria-hidden="true">${esc(EMOJI[ko])}</span>`;
  return "";
}
