// Builds purelift/kb/index.js (titles and summaries for the home page cards) from the article files
// purelift/kb/<id>.json, after checking each English/Chinese pair lines up block by block.
// Run after editing an article: node scripts/purelift-kb.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../purelift/kb/", import.meta.url);
// Card order on the home page: skincare, then treatments, then skin concerns.
const ORDER = [
  "retinol", "vitamin-c", "niacinamide", "glutathione",
  "microneedling", "microneedling-collagen", "aha-peels", "injectable-ha", "pn-polynucleotides", "prp-hair", "prp-skin-hair", "botulinum-toxin",
  "skin-barrier", "dry-skin-fine-lines", "fine-line-types", "pores-marks-scars", "facial-ageing",
];
const CATS = new Set(["skincare", "treatment", "concern"]);
const TYPES = new Set(["p", "h", "h3", "ul", "ol", "table", "warn", "note"]);

export function checkArticle(a) {
  const problems = [];
  if (!/^[a-z0-9-]+$/.test(a.id)) problems.push("id must be kebab-case");
  if (!CATS.has(a.category)) problems.push(`unknown category ${a.category}`);
  if (typeof a.review !== "boolean") problems.push("review must be true or false");
  for (const l of ["en", "zh"]) for (const k of ["title", "summary"]) if (!a[l]?.[k]) problems.push(`${l}.${k} missing`);
  const zb = a.zh.blocks, eb = a.en.blocks;
  if (zb.length !== eb.length) problems.push(`zh has ${zb.length} blocks, en has ${eb.length}`);
  zb.forEach((z, i) => {
    const e = eb[i];
    if (!e) return;
    if (!TYPES.has(z.t)) problems.push(`block ${i}: unknown type ${z.t}`);
    if (z.t !== e.t) problems.push(`block ${i}: zh ${z.t} vs en ${e.t}`);
    if ((z.t === "ul" || z.t === "ol") && z.items.length !== e.items?.length) problems.push(`block ${i}: list lengths differ`);
    if (z.t === "table" && (z.head.length !== e.head?.length || z.rows.length !== e.rows?.length || z.rows.some((r, j) => r.length !== e.rows[j]?.length))) problems.push(`block ${i}: table shapes differ`);
    for (const text of [z, e].flatMap((b) => [b.text, ...(b.items ?? []), ...(b.head ?? []), ...(b.rows ?? []).flat()]).filter(Boolean)) {
      if ((text.match(/\*\*/g) ?? []).length % 2) problems.push(`block ${i}: unbalanced ** in "${text.slice(0, 30)}…"`);
    }
  });
  return problems;
}

export function loadArticles() {
  return readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(new URL(f, dir), "utf8")));
}

export function buildIndex(articles) {
  const byId = new Map(articles.map((a) => [a.id, a]));
  const ids = [...ORDER.filter((id) => byId.has(id)), ...[...byId.keys()].filter((id) => !ORDER.includes(id)).sort()];
  return ids.map((id) => {
    const a = byId.get(id);
    return { id, category: a.category, review: a.review, en: { title: a.en.title, summary: a.en.summary }, zh: { title: a.zh.title, summary: a.zh.summary } };
  });
}

export const indexSource = (index) =>
  `// Generated by scripts/purelift-kb.mjs from purelift/kb/*.json. Edit the article files, then run that script.\nexport const ARTICLES = ${JSON.stringify(index, null, 1)};\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const articles = loadArticles();
  const bad = articles.flatMap((a) => checkArticle(a).map((p) => `${a.id}: ${p}`));
  if (bad.length) { console.error(bad.join("\n")); process.exit(1); }
  const index = buildIndex(articles);
  writeFileSync(new URL("index.js", dir), indexSource(index));
  console.log(`purelift/kb/index.js: ${index.length} articles (${index.filter((a) => a.review).length} held for review)`);
}
